const GLIFI = {};
for (const [c, righe] of Object.entries(G)) GLIFI[c] = righe.split('|');

function glifo(c) {
    if (GLIFI[c]) return GLIFI[c];
    const semplice = c.normalize('NFD').replace(/\p{M}/gu, '');
    if (GLIFI[semplice]) return GLIFI[semplice];
    if (GLIFI[c.toUpperCase()]) return GLIFI[c.toUpperCase()];
    return GLIFI['?'];
}

// Il "corpo" è la dimensione del carattere in pixel (come l'em di un font):
// le maiuscole sono alte circa il 72% del corpo.
function unita(corpo) { return corpo * 0.72 / 7; }

export function misuraTesto(testo, corpo) {
    const u = unita(corpo);
    const n = [...testo].length;
    return { larghezza: Math.max(0, n * 6 - 1) * u, altezza: 7 * u };
}

export function disegnaTesto(img, testo, x0, y0, corpo, colore = [255, 255, 255]) {
    const { larghezza: W, altezza: H, dati } = img;
    const u = unita(corpo);
    const grasso = u * 0.32;          // ingrossa i tratti in orizzontale
    const caratteri = [...testo];
    const larghezzaTot = caratteri.length * 6 * u + grasso;
    const altezzaTot = 9 * u;
    const bx = Math.max(0, Math.floor(x0)), by = Math.max(0, Math.floor(y0));
    const bw = Math.min(W, Math.ceil(x0 + larghezzaTot) + 1) - bx;
    const bh = Math.min(H, Math.ceil(y0 + altezzaTot) + 1) - by;
    if (bw <= 0 || bh <= 0) return img;
    const copertura = new Float32Array(bw * bh);

    const rettangolo = (rx0, ry0, rx1, ry1) => {
        const px0 = Math.max(bx, Math.floor(rx0)), px1 = Math.min(bx + bw - 1, Math.ceil(rx1) - 1);
        const py0 = Math.max(by, Math.floor(ry0)), py1 = Math.min(by + bh - 1, Math.ceil(ry1) - 1);
        for (let py = py0; py <= py1; py++) {
            const cy = Math.min(py + 1, ry1) - Math.max(py, ry0);
            if (cy <= 0) continue;
            for (let px = px0; px <= px1; px++) {
                const cx = Math.min(px + 1, rx1) - Math.max(px, rx0);
                if (cx <= 0) continue;
                const i = (py - by) * bw + (px - bx);
                copertura[i] = Math.min(1, copertura[i] + cx * cy);
            }
        }
    };

    caratteri.forEach((c, k) => {
        const righe = glifo(c);
        const gx = x0 + k * 6 * u;
        for (let r = 0; r < righe.length; r++) {
            const riga = righe[r];
            // unisce i pixel accesi consecutivi in un solo tratto: niente cuciture
            let inizio = -1;
            for (let col = 0; col <= 5; col++) {
                const acceso = col < 5 && riga[col] === '#';
                if (acceso && inizio < 0) inizio = col;
                if (!acceso && inizio >= 0) {
                    rettangolo(gx + inizio * u, y0 + r * u, gx + col * u + grasso, y0 + (r + 1) * u);
                    inizio = -1;
                }
            }
        }
    });

    for (let py = 0; py < bh; py++) {
        for (let px = 0; px < bw; px++) {
            const a = copertura[py * bw + px];
            if (a <= 0) continue;
            const o = ((py + by) * W + (px + bx)) * 4;
            dati[o] = Math.round(dati[o] * (1 - a) + colore[0] * a);
            dati[o + 1] = Math.round(dati[o + 1] * (1 - a) + colore[1] * a);
            dati[o + 2] = Math.round(dati[o + 2] * (1 - a) + colore[2] * a);
        }
    }
    return img;
}
